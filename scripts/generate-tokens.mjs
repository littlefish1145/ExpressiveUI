import { readFile, writeFile, mkdir } from 'node:fs/promises';
const ref = JSON.parse(await readFile('docs/references/sources.json', 'utf8'));
const base = `https://github.com/androidx/androidx/blob/${ref.refs.compose.sha}/compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/tokens/`;
const tokens = {};
for (const scheme of ['Expressive', 'Standard']) {
  const source = await readFile(`docs/references/compose-${scheme}MotionTokens.kt`, 'utf8');
  tokens[scheme.toLowerCase()] = {};
  for (const speed of ['Fast', 'Default', 'Slow'])
    for (const kind of ['Spatial', 'Effects']) {
      const read = (property) =>
        Number(source.match(new RegExp(`Spring${speed}${kind}${property} = ([\\d.]+)f`))[1]);
      tokens[scheme.toLowerCase()][`${speed.toLowerCase()}.${kind.toLowerCase()}`] = {
        stiffness: read('Stiffness'),
        dampingRatio: read('Damping'),
      };
    }
}
const buttons = {};
for (const [key, name] of Object.entries({
  xs: 'XSmall',
  sm: 'Small',
  md: 'Medium',
  lg: 'Large',
  xl: 'XLarge',
})) {
  const source = await readFile(`docs/references/compose-Button${name}Tokens.kt`, 'utf8');
  const read = (property) =>
    Number(source.match(new RegExp(`${property}:.*\\s*get\\(\\) = ([\\d.]+).dp`))[1]);
  const shapes = {
    CornerFull: 'full',
    CornerMedium: 12,
    CornerLarge: 16,
    CornerExtraLarge: 28,
    CornerSmall: 8,
  };
  const shape = (property) =>
    shapes[source.match(new RegExp(`${property}:.*\\s*get\\(\\) = ShapeKeyTokens.(\\w+)`))[1]];
  buttons[key] = {
    height: read('ContainerHeight'),
    padding: read('LeadingSpace'),
    icon: read('IconSize'),
    gap: read('IconLabelSpace'),
    outline: read('OutlinedOutlineWidth'),
    square: shape('ContainerShapeSquare'),
    pressed: shape('PressedContainerShape'),
  };
}
const swSource = await readFile('docs/references/compose-SwitchTokens.kt', 'utf8');
const switchTokens = Object.fromEntries(
  [
    'TrackHeight',
    'TrackWidth',
    'TrackOutlineWidth',
    'SelectedHandleWidth',
    'UnselectedHandleWidth',
    'PressedHandleWidth',
    'StateLayerSize',
  ].map((p) => [
    p[0].toLowerCase() + p.slice(1),
    Number(swSource.match(new RegExp(`${p}:.*\\s*get\\(\\) = ([\\d.]+).dp`))[1]),
  ]),
);
const ts = `// Generated by scripts/generate-tokens.mjs from pinned AndroidX sources. Apache-2.0.\nexport const motionTokens = ${JSON.stringify(tokens, null, 2)} as const;\nexport const buttonTokens = ${JSON.stringify(buttons, null, 2)} as const;\nexport const switchTokens = ${JSON.stringify(switchTokens, null, 2)} as const;\nexport const cornerTokens = {none:0, extraSmall:4, small:8, medium:12, large:16, largeIncreased:20, extraLarge:28, extraLargeIncreased:32, extraExtraLarge:48, full:Infinity} as const;\nexport type MotionScheme = keyof typeof motionTokens;\nexport type MotionToken = keyof typeof motionTokens.expressive;\nexport type ButtonSize = keyof typeof buttonTokens;\nexport * from './controls.js';\nexport * from './catalog.js';\n`;
const css =
  '/* Generated; dp mapped to CSS px. */\n:root {\n' +
  Object.entries(buttons)
    .flatMap(([size, values]) =>
      Object.entries(values).map(([key, v]) => `  --md-ref-button-${size}-${key}: ${v}px;`),
    )
    .join('\n') +
  '\n  --md-sys-shape-corner-small: 8px;\n  --md-sys-shape-corner-medium: 12px;\n  --md-sys-shape-corner-large: 16px;\n  --md-sys-shape-corner-extra-large: 28px;\n}\n';
await mkdir('packages/tokens/src', { recursive: true });
for (const [file, content] of [
  ['index.ts', ts],
  ['styles.css', css],
]) {
  const path = `packages/tokens/src/${file}`;
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== content) throw Error(`Stale generated file: ${path}`);
  } else await writeFile(path, content);
}
await writeFile(
  'docs/references/token-values.json',
  JSON.stringify(
    {
      motion: tokens,
      buttons,
      switch: switchTokens,
      sources: {
        motion: [base + 'ExpressiveMotionTokens.kt', base + 'StandardMotionTokens.kt'],
        buttons: base + 'Button{Size}Tokens.kt',
        switch: base + 'SwitchTokens.kt',
        corners: base + 'ShapeTokens.kt',
      },
    },
    null,
    2,
  ) + '\n',
);
console.log('Verified official motion, button and switch token extraction.');
