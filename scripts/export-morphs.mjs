// Run after export-shapes.mjs. Uses the actual official feature-aware Morph implementation.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { resolve, delimiter } from 'node:path';
const dir = resolve('.cache/shape-export');
const original = await readFile(`${dir}/Export.kt`, 'utf8');
const body = original.slice(0, original.indexOf('\nfun main()'));
const source = await readFile('docs/references/compose-MaterialShapes.kt', 'utf8');
const names = [...source.matchAll(/public val (\w+): RoundedPolygon/g)].map((m) => m[1]);
const main = `
fun encode(c:List<Cubic>)=c.joinToString(",","[","]"){ listOf(it.anchor0X,it.anchor0Y,it.control0X,it.control0Y,it.control1X,it.control1Y,it.anchor1X,it.anchor1Y).joinToString(",") }
fun main() {
 val shapes=listOf(${names.map((n) => `"${n[0].toLowerCase() + n.slice(1)}" to MaterialShapes.${n}`).join(',')})
 println("{\\\"pairs\\\":{")
 var first=true
 for((name,a) in shapes)for((other,b)in shapes) { if(name==other)continue
  if(!first)print(",")
  val morph=Morph(a,b)
  print("\\\""+name+"|"+other+"\\\":["+encode(morph.asCubics(0f))+","+encode(morph.asCubics(1f))+"]")
  first=false
 }
 println("},\\\"bounds\\\":{")
 first=true
 for((name,p)in shapes) {
  if(!first)print(",")
  val bounds=p.calculateBounds();val max=p.calculateMaxBounds()
  print("\\\""+name+"\\\":{\\\"bounds\\\":"+bounds.joinToString(",","[","]")+",\\\"maxBounds\\\":"+max.joinToString(",","[","]")+"}")
  first=false
 }
 println("}}")
}
`;
await writeFile(`${dir}/MorphExport.kt`, body + main);
const jars = [
  'compiler.jar',
  'stdlib.jar',
  'script.jar',
  'reflect.jar',
  'trove.jar',
  'coroutines.jar',
  'annotations.jar',
  'collection.jar',
  'classes.jar',
];
const cp = jars.map((n) => `${dir}/${n}`).join(delimiter);
execFileSync(
  'java',
  [
    '-cp',
    cp,
    'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler',
    '-no-stdlib',
    '-no-reflect',
    '-classpath',
    cp,
    '-d',
    `${dir}/morph-export.jar`,
    `${dir}/MorphExport.kt`,
  ],
  { stdio: 'inherit' },
);
const data = JSON.parse(
  execFileSync('java', ['-cp', [`${dir}/morph-export.jar`, cp].join(delimiter), 'MorphExportKt'], {
    encoding: 'utf8',
    maxBuffer: 128 * 1024 * 1024,
  }),
);
const round = (_k, v) => (typeof v === 'number' ? Math.round(v * 1e7) / 1e7 : v);
const header =
  '// Copyright 2024 The Android Open Source Project. Apache-2.0.\n// Generated by scripts/export-morphs.mjs using official graphics-shapes 1.0.1.\n';
await mkdir('packages/shape/src/morph-data', { recursive: true });
const sequence = ['softBurst', 'cookie9Sided', 'pentagon', 'pill', 'sunny', 'cookie4Sided', 'oval'];
const loadingKeys = sequence.map((name, i) => name + '|' + sequence[(i + 1) % sequence.length]);
const imports = [],
  statics = [],
  dynamic = [];
for (const [key, pair] of Object.entries(data.pairs)) {
  const name = key.replace('|', '-');
  await writeFile(
    `packages/shape/src/morph-data/${name}.ts`,
    header +
      'const data: readonly [readonly number[],readonly number[]] = ' +
      JSON.stringify(pair, round) +
      ';\nexport default data;\n',
  );
  if (loadingKeys.includes(key)) {
    const variable = 'pair' + statics.length;
    imports.push(`import ${variable} from './morph-data/${name}.js';`);
    statics.push(`'${key}':${variable}`);
  } else dynamic.push(`'${key}':()=>import('./morph-data/${name}.js')`);
}
await writeFile(
  'packages/shape/src/morph-data-index.ts',
  header +
    imports.join('\n') +
    '\nexport const loadingMorphs:Record<string,readonly [readonly number[],readonly number[]]>={' +
    statics.join(',') +
    '};\n',
);
await writeFile(
  'packages/shape/src/morph-loaders.ts',
  header +
    'export const morphLoaders:Record<string,()=>Promise<{default:readonly [readonly number[],readonly number[]]}>>={' +
    dynamic.join(',') +
    '};\n',
);
await writeFile('docs/references/material-morphs.json', JSON.stringify(data.pairs, round));
await writeFile(
  'packages/shape/src/material-bounds.ts',
  header +
    'export const materialBounds: Record<string,{bounds:readonly number[];maxBounds:readonly number[]}> = ' +
    JSON.stringify(data.bounds, round) +
    ';\n',
);
console.log(
  'Exported',
  Object.keys(data.pairs).length,
  'directed official morph matches and',
  Object.keys(data.bounds).length,
  'bounds.',
);
